//! Regras do Rapidgator (`[rapidgator]` em `rules/hosts.toml`): endereços,
//! padrões das páginas, textos de cada situação, esperas e limites.

use serde::Deserialize;

#[derive(Debug, Clone, Deserialize)]
pub struct RapidgatorRules {
    pub hosts: Vec<String>,
    /// Origem dos pedidos (`https://rapidgator.net`): links de outros
    /// domínios do servidor são normalizados para ela.
    pub origin: String,
    pub file_pattern: String,
    pub folder_pattern: String,
    /// Cookie mandado em todas as páginas (`lang=en`: textos em inglês).
    pub cookie: String,
    pub name_pattern: String,
    pub size_pattern: String,
    pub var_pattern: String,
    pub start_timer_path: String,
    pub get_link_path: String,
    pub captcha_path: String,
    pub timer_ok: String,
    pub link_ok: String,
    pub fallback_countdown_secs: u64,
    pub max_countdown_secs: u64,
    pub countdown_margin_secs: u64,
    pub captcha_form_selector: String,
    pub answer_fields: Vec<String>,
    pub turnstile_sitekey_pattern: String,
    pub captcha_deadline_secs: u64,
    pub captcha_min_left_secs: u64,
    pub late_captcha_cookie: String,
    pub late_captcha_wait_minutes: u64,
    pub final_link_patterns: Vec<String>,
    pub wrong_captcha_markers: Vec<String>,
    pub offline_markers: Vec<String>,
    pub premium_markers: Vec<String>,
    pub free_size_pattern: String,
    pub delay_pattern: String,
    pub hourly_markers: Vec<String>,
    pub hourly_wait_minutes: u64,
    pub daily_markers: Vec<String>,
    pub one_at_a_time_markers: Vec<String>,
    pub one_at_a_time_wait_minutes: u64,
    pub unavailable_markers: Vec<String>,
    pub unavailable_wait_minutes: u64,
    pub state_error_wait_minutes: u64,
    pub cloudflare_markers: Vec<String>,
    pub free_connections: u16,
    pub free_resumable: bool,
    pub free_max_active: usize,
    pub folder_file_pattern: String,
    pub folder_sub_pattern: String,
    pub folder_page_pattern: String,
    pub folder_missing_markers: Vec<String>,
    pub folder_page_delay_ms: u64,
    pub folder_max_pages: u32,
    pub api_path: String,
    pub api_login: String,
    pub api_user_info: String,
    pub api_file_info: String,
    pub api_file_download: String,
    pub session_minutes: u64,
    pub api_wait_markers: Vec<String>,
    pub api_wait_minutes: u64,
    pub api_bad_login_markers: Vec<String>,
    pub api_unusual_ip_markers: Vec<String>,
    pub api_2fa_markers: Vec<String>,
    pub api_locked_markers: Vec<String>,
    pub traffic_wait_minutes: u64,
    pub paid_markers: Vec<String>,
    pub premium_connections: u16,
    pub premium_resumable: bool,
}
